#!/usr/bin/env python3
"""Transcribe audit §9.1 / §9.2 into the two payload sources, mechanically.

    artifacts/dtbo/transcribe_audit.py [--audit artifacts/reports/pps_runtime_audit.md]
                                       [--check]

Writes (or with --check, only compares):
    tools/pps-dtbo/payload/pps_props.txt     <- §9.1 "Scalars / arrays"
    tools/pps-dtbo/payload/pps_subtree.dts   <- §9.2 "Curve subtree"

The point is that the payload is copied *by machine* from the audit, so a
transcription typo is impossible and "did we follow the audit verbatim?" is
answered by running this with --check. build.sh does not run it: src/ stays the
source of truth for the build, but --check is wired in as a warning.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def read_audit(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def section(text, heading):
    """Return the text of the first ```dts fenced block under `heading`."""
    start = text.index(heading)
    fence = text.index("```dts", start)
    body_start = text.index("\n", fence) + 1
    end = text.index("```", body_start)
    return text[body_start:end]


def strip_line_comment(line):
    """Remove a trailing /* ... */ comment, keep the code."""
    idx = line.find("/*")
    if idx < 0:
        return line.rstrip(), None
    return line[:idx].rstrip(), line[idx:].strip()


def convert_props(block):
    """§9.1 dts block -> pps_props.txt lines."""
    out = []
    for raw in block.split("\n"):
        line, comment = strip_line_comment(raw)
        s = line.strip()
        if not s:
            if comment and comment.startswith("/* ----"):
                out.append("")
                out.append("# " + comment.strip("/* ").strip(" -"))
            continue
        if not s.endswith(";"):
            raise SystemExit("unparsed §9.1 line: %r" % raw)
        s = s[:-1].strip()
        name, _, value = s.partition("=")
        name = name.strip()
        value = value.strip()
        if not name:
            raise SystemExit("no property name in %r" % raw)
        if value.startswith('"'):
            out.append('str:%s=%s' % (name, value))
        elif value.startswith("<") and value.endswith(">"):
            cells = [c for c in re.split(r"[\s,]+", value[1:-1].strip()) if c]
            if not cells:
                raise SystemExit("empty value for %s" % name)
            out.append("%s=%s" % (name, ",".join(cells)))
        else:
            raise SystemExit("unexpected value %r for %s" % (value, name))
    return out


def convert_subtree(block):
    """§9.2 dts block -> a standalone, compilable .dts (verbatim + wrapper)."""
    body = block.rstrip("\n")
    header = """\
/dts-v1/;

/*
 * GENERATED by artifacts/dtbo/transcribe_audit.py from
 * artifacts/reports/pps_runtime_audit.md §9.2 -- verbatim, do not hand edit.
 *
 * v1 grammar (oplus_pps.c:212-228, :889-950): 6 soc children
 *   strategy_soc_range_{min,low,mid_low,mid,mid_high,high}, each with the 6
 *   strategy_temp_{little_cold,cool,little_cool,normal_low,normal_high,warm}
 *   arrays of <target_vbus target_vbat target_ibus exit target_time> 5-tuples.
 * Note: no oplus,soc_range / oplus,temp_range child properties -- v1 does not
 * parse them and audit §9.2 does not list them.
 */

/ {
"""
    return header + body + "\n};\n"


def main(argv):
    audit = os.path.join(HERE, "..", "..", "artifacts", "reports",
                         "pps_runtime_audit.md")
    if "--audit" in argv:
        audit = argv[argv.index("--audit") + 1]
    check = "--check" in argv

    text = read_audit(audit)
    props_block = section(text, "### 9.1")
    subtree_block = section(text, "### 9.2")

    props = convert_props(props_block)
    subtree = convert_subtree(subtree_block)

    prelude = """\
# PPS payload: scalar / string properties, spliced into the __overlay__ of
# &battery_charger (the node that already carries qcom,pd_input_current_charger_ma;
# its fragment index differs per dtbo entry: /fragment@47 in 02/04, /fragment@42 in 08).
#
# GENERATED by artifacts/dtbo/transcribe_audit.py from
# artifacts/reports/pps_runtime_audit.md §9.1 -- verbatim, do not hand edit.
#
# Format: NAME=VAL (u32 or u32 array, comma separated), NAME= (empty property),
#         str:NAME="TEXT" (NUL terminated string).
#
# NOT part of audit §9.1, kept deliberately: see the block at the bottom.
"""
    extra = """
# --- not in audit §9.1: pre-existing stock property we must not regress ----
# This is not a PPS property. It is what produced the measured 27 W and it is
# already live on the device; leaving it at the stock 2000 would *regress* the
# image. Audit §9.1 scopes itself to PPS, so its absence there is expected.
# Delete this line if a strictly §9.1-only payload is ever wanted.
qcom,pd_input_current_charger_ma=3000
"""
    props_text = prelude + "\n".join(props) + "\n" + extra

    targets = [(os.path.join(HERE, "payload", "pps_props.txt"), props_text),
               (os.path.join(HERE, "payload", "pps_subtree.dts"), subtree)]
    rc = 0
    for path, content in targets:
        if check:
            old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if old != content:
                sys.stderr.write("MISMATCH vs audit: %s\n" % path)
                rc = 1
            else:
                print("ok (verbatim): %s" % os.path.basename(path))
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
            print("wrote %s (%d bytes)" % (os.path.basename(path), len(content)))
    return rc


if __name__ == "__main__":
    sys.exit(main(sys.argv))
