#!/usr/bin/env bash
# Regenerate the patched dtbo images for PPS on the OnePlus 11 (SM8550 / 22811).
#
#   tools/pps-dtbo/build.sh 1        stage 1: scalar + string properties only
#   tools/pps-dtbo/build.sh 2        stage 2: stage 1 + the pps_charge_third_strategy
#                                              curve subtree (src/pps_subtree.dts)
#
# Inputs (edit these, then re-run):
#   src/pps_props.txt      the scalar/string payload, one property per line
#   src/pps_subtree.dts    the curve subtree, compiled standalone with dtc -@
#
# Outputs:
#   out/stage<N>_*/entries/*.dtbo     all 9 entries (02/04/08 patched, 6 untouched)
#   out/stage<N>_*/dtbo.img           the complete flashable image
#   out/stage<N>_*/decompiles/*       per-blob original/patched dts + unified diff
#   out/stage<N>_*/summary.txt        byte-diff statistics for the report
#   src/pps_payload_full.dts          human readable view of what gets inserted
#
# The stock image is only ever read. The work/ entries are pristine copies of the
# stock entries and are never modified in place.
set -euo pipefail
export PYTHONDONTWRITEBYTECODE=1   # keep tools/dtbo free of __pycache__

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
REPO=$(cd "$HERE/../.." && pwd)
SRC="$HERE/payload"
WORK="$REPO/artifacts/dtbo/work"
TOOL="$REPO/tools/dtbo/fdt_splice.py"
REPACK="$REPO/tools/dtbo/dtbo_tool.py"
STOCK_IMG=${STOCK_IMG:-/home/aibeto/dtbo_stock.img}

STAGE=${1:-1}
UNITS="02 04 08"          # the entries whose msm-id (0x207/0x218) matches this phone
# The fragment index of the &battery_charger overlay is NOT the same in every
# entry (47 in 02/04, 42 in 08), so the node is addressed by the property it
# already carries instead of by a hard coded path.
ANCHOR=qcom,pd_input_current_charger_ma

case "$STAGE" in
  1) TAG=stage1_scalars ;;
  2) TAG=stage2_scalars_curve ;;
  *) echo "usage: $0 [1|2]" >&2; exit 2 ;;
esac

SDIR="$REPO/artifacts/dtbo/out/$TAG"
ENT="$SDIR/entries"
DEC="$SDIR/decompiles"
mkdir -p "$ENT" "$DEC"

say() { printf '\n=== %s\n' "$*"; }

# ---------------------------------------------------------------- 0. stock entries
if [ ! -f "$WORK/manifest.json" ]; then
  say "extracting stock image $STOCK_IMG into $WORK (read only source)"
  python3 "$REPACK" extract "$STOCK_IMG" "$WORK"
fi

mapfile -t FILES < <(python3 - "$WORK/manifest.json" <<'PY'
import json, sys
m = json.load(open(sys.argv[1]))
for e in m["entries"]:
    print(e["file"])
PY
)
[ "${#FILES[@]}" -eq 9 ] || { echo "expected 9 entries in the manifest, got ${#FILES[@]}" >&2; exit 1; }

# ---------------------------------------------------------------- 1. payload args
say "payload: $SRC/pps_props.txt"
PROP_ARGS=()
while IFS= read -r raw || [ -n "$raw" ]; do
  line=${raw%%#*}                       # strip comments
  line=$(printf '%s' "$line" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')
  [ -z "$line" ] && continue
  case "$line" in
    str:*) PROP_ARGS+=(--setstr "${line#str:}") ;;
    *)     PROP_ARGS+=(--set "$line") ;;
  esac
done < "$SRC/pps_props.txt"

SPLICE_ARGS=()
if [ "$STAGE" = "2" ]; then
  say "compiling $SRC/pps_subtree.dts -> work/pps_subtree.dtbo"
  dtc -@ -I dts -O dtb -o "$WORK/pps_subtree.dtbo" "$SRC/pps_subtree.dts" \
      >"$SDIR/pps_subtree.dtc.log" 2>&1
  python3 "$TOOL" --verify-only "$WORK/pps_subtree.dtbo" \
      > "$SDIR/pps_subtree.verify.txt"
  SPLICE_ARGS=(--splice "$WORK/pps_subtree.dtbo")
fi

# ---------------------------------------------------------------- 1b. validation
say "validating the payload against audit §9.1 / §9.2"
if [ "$STAGE" = "2" ]; then
  python3 "$HERE/validate_payload.py" --props "$SRC/pps_props.txt" \
      --subtree "$WORK/pps_subtree.dtbo"
else
  python3 "$HERE/validate_payload.py" --props "$SRC/pps_props.txt" --subtree ""
fi
# non fatal: tells you when src/ has drifted from the audit text
python3 "$HERE/transcribe_audit.py" --check \
    || echo "WARN: src/ differs from audit §9.1/§9.2 (fine if the edit was intentional)"

# ---------------------------------------------------------------- 2. reviewable output
python3 - "$SRC" "$STAGE" > "$SRC/pps_payload_full.dts.tmp" <<'PY'
import re, sys
src, stage = sys.argv[1], sys.argv[2]
print("/* GENERATED by tools/pps-dtbo/build.sh -- do not edit, edit pps_props.txt")
print(" * and pps_subtree.dts instead.\n *")
print(" * This is exactly what gets inserted into /fragment@47/__overlay__")
print(" * (== &battery_charger) of dtbo entries 02 / 04 / 08.\n */\n")
print("&battery_charger {   /* the __overlay__ that carries qcom,pd_input_current_charger_ma */")
for raw in open(src + "/pps_props.txt"):
    line = raw.split("#", 1)[0].strip()
    if not line:
        continue
    if line.startswith("str:"):
        name, _, val = line[4:].partition("=")
        print("\t%s = %s;" % (name, val))
    else:
        name, _, val = line.partition("=")
        if val == "":
            print("\t%s;" % name)
        else:
            cells = " ".join(("0x%X" % int(c, 0)) if int(c, 0) > 9 else str(int(c, 0))
                             for c in val.split(","))
            print("\t%s = <%s>;" % (name, cells))
if stage == "2":
    print("")
    body = open(src + "/pps_subtree.dts").read()
    body = body.split("\n/ {", 1)[1]              # drop /dts-v1/ and the root open
    body = body.rsplit("};", 1)[0]                # drop the root close
    for line in body.split("\n"):
        if line.strip() == "":
            continue
        print(line)
print("};")
PY
mv -f "$SRC/pps_payload_full.dts.tmp" "$SRC/pps_payload_full.dts"

# ---------------------------------------------------------------- 3. stage the entries
say "staging 9 entries into $ENT"
cp -f "$WORK/manifest.json" "$ENT/manifest.json"
for f in "${FILES[@]}"; do
  cp -f "$WORK/$f" "$ENT/$f"
done

# ---------------------------------------------------------------- 4. patch 02/04/08
for f in "${FILES[@]}"; do
  idx=${f%%_*}
  case " $UNITS " in *" $idx "*) ;; *) continue ;; esac
  say "patching entry $idx ($f)"
  python3 "$TOOL" "$WORK/$f" "$ENT/$f" \
      --anchor-prop "$ANCHOR" \
      "${PROP_ARGS[@]}" \
      ${SPLICE_ARGS[@]+"${SPLICE_ARGS[@]}"} \
      --force --quiet --dts-dir "$DEC"
  python3 "$HERE/verify_payload.py" "$WORK/$f" "$ENT/$f" "$STAGE"
done

# ---------------------------------------------------------------- 5. untouched entries
say "checking the 6 non-matching entries are byte identical to stock"
for f in "${FILES[@]}"; do
  idx=${f%%_*}
  case " $UNITS " in *" $idx "*) continue ;; *) ;; esac
  cmp "$WORK/$f" "$ENT/$f" || { echo "entry $idx was modified!" >&2; exit 1; }
done
echo "ok: entries 00 01 03 05 06 07 are untouched"

# ---------------------------------------------------------------- 6. repack
say "repacking $SDIR/dtbo.img"
python3 "$REPACK" repack "$ENT" "$SDIR/dtbo.img"

# ---------------------------------------------------------------- 7. round trip check
say "verifying the packed image by extracting it again"
mkdir -p "$SDIR/verify"
python3 "$REPACK" extract "$SDIR/dtbo.img" "$SDIR/verify" > "$SDIR/verify/extract.log"
for f in "${FILES[@]}"; do
  cmp "$ENT/$f" "$SDIR/verify/$f" || { echo "repack round trip mismatch on $f" >&2; exit 1; }
done
cmp "$ENT/manifest.json" "$SDIR/verify/manifest.json" || true
echo "ok: all 9 entries survive the repack round trip"

# ---------------------------------------------------------------- 8. summary
say "summary"
{
  echo "stage            : $STAGE ($TAG)"
  echo "payload          : src/pps_props.txt$([ "$STAGE" = 2 ] && echo ' + src/pps_subtree.dts')"
  echo "target node      : the __overlay__ carrying $ANCHOR (fragment index differs per entry)"
  echo "patched entries  : $UNITS"
  echo "image            : out/$TAG/dtbo.img"
  echo
  for f in "${FILES[@]}"; do
    idx=${f%%_*}
    case " $UNITS " in *" $idx "*) ;; *) continue ;; esac
    printf 'entry %s: %s\n' "$idx" "$(stat -c '%s' "$ENT/$f") bytes (stock $(stat -c '%s' "$WORK/$f"))"
    for d in "$DEC/${f%.dtbo}".*.diff.txt; do
      [ -f "$d" ] || continue
      # '+' lines minus the single '+++' header; blank added lines are just '+'
      printf '  %s: %s added / %s removed line(s)\n' \
        "$(basename "$d")" \
        "$(($(grep -c '^+' "$d" || true) - 1))" "$(grep -c '^-[^-]' "$d" || true)"
    done
  done
  echo
  echo "image size       : $(stat -c '%s' "$SDIR/dtbo.img") bytes"
  echo "stock image size : $(stat -c '%s' "$STOCK_IMG") bytes"
} | tee "$SDIR/summary.txt"

say "done: $SDIR/dtbo.img"
